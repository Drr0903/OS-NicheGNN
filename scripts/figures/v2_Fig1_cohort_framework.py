"""v2 Figure 1 — cohort, network, region reference labels and the biological readouts of the atlas.
a  cohort: diagnostic bone biopsies, relapsed lesions at four sites, patient-level hold-out and the independent datasets
b  the network: two neighbourhood branches fused by a mixture of two MLP experts, latent, decoder and training objective
c  example section (MR11B): H&E and the algorithmic region reference labels with the tumour–lung interface
d  from the niche atlas to biology: niche and router-weight maps of MR2 and the three biological readouts
Panels a, b and d are drawn by v2_Fig1_overview (icons in figures/source_data/Fig1_icons, generated by fig1_icons_generate.py).
The patient → section hierarchy of the cohort is Supplementary Figure S1.
Reads results/04b_panel_exports/, results/35_representative_interface/ and results/15_niches/meta.json.
"""
from __future__ import annotations

import json

import sys
from importlib import import_module
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.patches import Rectangle
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1])); sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.plotting import PALETTE, REGION_COL, save_fig, save_source, set_style  # noqa: E402
from lib.repro import ROOT  # noqa: E402

NAME = "Fig1"
ov = import_module("v2_Fig1_overview")  # the overview panel is drawn by its own module


def panel_c(ax, x0, y0, x1, y1, section: str = "MR11B"):
    """H&E and the algorithmic region labels, both read from the stage-04b export (no raw data needed), in millimetres"""
    sd = ROOT / "results/04b_panel_exports"
    img = np.asarray(Image.open(sd / f"{section}_hires_crop.png").convert("RGB")); d = pd.read_csv(sd / f"{section}_spots.tsv", sep="\t")
    p = ov.frame(ax, x0, y0, x1, y1, "#f3f5f7", f"Region reference labels ({section})")
    w = (x1 - x0 - 9) / 2; h = w * img.shape[0] / img.shape[1]; yb = (y0 + 9 + y1 - 9) / 2 - h / 2 + 1
    for k, lab in enumerate(["H&E", "algorithmic labels + interface"]):
        xx = x0 + 3 + k * (w + 3); ov.D.image(ax, img, xx, yb, w) if k == 0 else None
        if k == 1:
            ax.add_patch(Rectangle((xx, yb), w, h, fc="white", ec="#c9d1d8", lw=0.5, zorder=4)); ax.imshow(img, extent=[xx, xx + w, yb, yb + h], alpha=0.25, zorder=5)
            px = lambda v: xx + v / img.shape[1] * w; py = lambda v: yb + h - v / img.shape[0] * h  # noqa: E731
            for key, c in REGION_COL.items():
                m = (d["label"] == key).to_numpy()
                if m.any():
                    ax.scatter(px(d.loc[m, "x"]), py(d.loc[m, "y"]), s=0.5, c=c, linewidths=0, zorder=6)
            ifc = d["interface"].fillna(False).to_numpy(bool)
            ax.scatter(px(d.loc[ifc, "x"]), py(d.loc[ifc, "y"]), s=1.4, facecolors="none", edgecolors="black", linewidths=0.25, zorder=7)
        ov.txt(ax, xx + w / 2, yb + h + 2.2, lab, p, fs=6.0)
    items = [(REGION_COL["tumor_cellular"], "tumour"), (REGION_COL["lung_parenchyma"], "lung parenchyma"), (REGION_COL["paucicellular"], "stroma/other"), (None, "interface")]
    for k, (c, lab) in enumerate(items):
        xx = x0 + 5 + [0, 16, 41, 62][k]; yy = yb - 5.0
        ax.scatter([xx], [yy], s=6, c=c if c else "none", edgecolors="black" if c is None else "none", linewidths=0.4, zorder=7); ov.txt(ax, xx + 2, yy, lab, p, fs=5.6, ha="left")
    save_source(d, NAME, "c")


def overview_inputs(section: str = "MR2"):
    sd = ROOT / "results/35_representative_interface"; img = np.asarray(Image.open(sd / f"{section}_hires_crop.png").convert("RGB"))
    d = pd.read_csv(sd / f"{section}_spots.tsv", sep="\t"); d = d[~d["unmatched"].fillna(True).astype(bool)].copy(); d["niche_c"] = d["niche"].astype(int)
    K = json.load(open(ROOT / "results/15_niches/meta.json"))["K"]; save_source(d[["barcode", "x", "y", "niche", "host_expert_weight"]], NAME, "a")
    return img, d, {k: PALETTE[k % len(PALETTE)] for k in range(K)}


def check_containment(fig):
    """every label drawn into a box must lie inside it"""
    r = fig.canvas.get_renderer(); bad = []
    for t, p in ov.D.PAIRS:
        tb, pb = t.get_window_extent(r), p.get_window_extent(r)
        if tb.x0 < pb.x0 - 0.5 or tb.x1 > pb.x1 + 0.5 or tb.y0 < pb.y0 - 0.5 or tb.y1 > pb.y1 + 0.5:
            bad.append(t.get_text().replace("\n", " "))
    assert not bad, f"labels outside their box: {bad}"


def main() -> None:
    set_style(); W, H = 180.0, 198.0
    fig = plt.figure(figsize=(W / 25.4, H / 25.4)); ax = fig.add_axes([0, 0, 1, 1])
    ys = ov.draw(ax, *overview_inputs(), W, H); panel_c(ax, 6, ys["cd"][0], 90, ys["cd"][1])
    for letter, x, y in [("a", 1.0, ys["a"][1]), ("b", 1.0, ys["b"][1]), ("c", 1.0, ys["cd"][1]), ("d", 91.5, ys["cd"][1])]:
        ax.text(x, y, letter, fontsize=9, fontweight="bold", va="top", ha="left", color="black")
    fig.canvas.draw(); check_containment(fig)
    save_fig(fig, f"{NAME}_cohort_framework")


if __name__ == "__main__":
    main()
